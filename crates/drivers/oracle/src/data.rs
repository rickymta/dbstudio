/// Column types the OCI binding cannot read; they are converted in the select list.
fn select_expr(column: &str, data_type: &str) -> Result<(String, bool)> {
    let q = quote_ident(column)?;
    let t = data_type.to_ascii_uppercase();
    Ok(match t.as_str() {
        "JSON" => (format!("JSON_SERIALIZE({q} RETURNING CLOB) AS {q}"), true),
        "VECTOR" => (format!("FROM_VECTOR({q}) AS {q}"), true),
        "BFILE" => (
            format!("CASE WHEN {q} IS NULL THEN NULL ELSE '<BFILE>' END AS {q}"),
            true,
        ),
        _ => (q, false),
    })
}

/// What is needed to page through one table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableMeta {
    pub select_list: String,
    /// Columns that make the order deterministic (key, or `ROWID`).
    pub tiebreak: Vec<String>,
    pub quoted_table: String,
    pub kind: ObjectKind,
}

/// Column list, key and kind of `schema.name`.
pub fn table_meta(
    conn: &Connection,
    schema: &str,
    name: &str,
    only: &[String],
    add_rowid: bool,
) -> Result<TableMeta> {
    let kind = catalog::relation_kind(conn, schema, name)?
        .ok_or_else(|| Error::NotFound(format!("table or view {schema}.{name}")))?;
    let cols = rows(
        conn,
        "SELECT column_name, data_type FROM all_tab_cols \
         WHERE owner = :1 AND table_name = :2 AND hidden_column = 'NO' AND column_id IS NOT NULL \
         ORDER BY column_id",
        &[&schema, &name],
    )?;
    let mut exprs = Vec::new();
    let mut rewritten = false;
    let wanted: Vec<&String> = only.iter().collect();
    for name in &wanted {
        if !cols.iter().any(|c| cell(c, 0) == **name) {
            return Err(Error::query(format!(
                "no column \"{name}\" in {schema}.{}",
                "the table"
            )));
        }
    }
    for c in &cols {
        let column = cell(c, 0);
        if !only.is_empty() && !only.contains(&column) {
            continue;
        }
        let (expr, changed) = select_expr(&column, &cell(c, 1))?;
        rewritten |= changed;
        exprs.push(expr);
    }
    // Key for deterministic paging.
    let tiebreak = if kind == ObjectKind::View {
        Vec::new()
    } else {
        let info = catalog::key_info(conn, schema, name)?;
        if !info.primary_key.is_empty() {
            info.primary_key
        } else if let Some(u) = info.unique_keys.first() {
            u.clone()
        } else {
            vec![ROWID.to_string()]
        }
    };
    let select_list = if rewritten || !only.is_empty() || add_rowid {
        let mut l = exprs;
        if add_rowid && tiebreak == [ROWID.to_string()] {
            l.push(format!("ROWID AS {}", quote_ident(ROWID)?));
        }
        l.join(", ")
    } else {
        "*".to_string()
    };
    Ok(TableMeta {
        select_list,
        tiebreak,
        quoted_table: qualified(schema, name)?,
        kind,
    })
}

/// Everything `fetch_table` needs, built on the worker.
#[allow(clippy::too_many_arguments)]
pub fn fetch_table_worker(
    conn: &Connection,
    schema: &str,
    name: &str,
    filters: &[ColumnFilter],
    raw_where: Option<&str>,
    sort: &[SortKey],
    offset: u64,
    limit: u64,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let meta = table_meta(conn, schema, name, &[], true)?;
    let sql = sql::select_sql(
        &meta.select_list,
        &meta.quoted_table,
        filters,
        raw_where,
        sort,
        &meta.tiebreak,
        offset,
        limit,
    )?;
    read_only_query(conn, &sql, batch, max_lob, em, ctl)
}

/// Run one `SELECT` generated by the driver inside `SET TRANSACTION READ ONLY` (a consistent
/// snapshot) and end the transaction afterwards.
pub fn read_only_query(
    conn: &Connection,
    sql: &str,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let _ = conn.execute("SET TRANSACTION READ ONLY", &[]);
    let params = ExecParams {
        text: String::new(),
        max_rows: None,
        batch_size: batch,
        auto_commit: false,
        read_only: false,
        max_lob,
        keep_open: false,
    };
    let result = run_single_query(conn, sql, &params, em, ctl);
    let _ = conn.rollback();
    result
}

/// `SELECT COUNT(*)` of a table with filters.
pub fn count_worker(
    conn: &Connection,
    schema: &str,
    name: &str,
    filters: &[ColumnFilter],
    raw_where: Option<&str>,
) -> Result<u64> {
    let table = qualified(schema, name)?;
    let sql = sql::count_sql(&table, filters, raw_where)?;
    let _ = conn.execute("SET TRANSACTION READ ONLY", &[]);
    let result = catalog::scalar(conn, &sql, &[]);
    let _ = conn.rollback();
    result?
        .and_then(|v| v.trim().parse::<u64>().ok())
        .ok_or_else(|| Error::Other("COUNT(*) returned no number".into()))
}

/// Stream a whole table (export / backup) on the connection, inside its current transaction.
#[allow(clippy::too_many_arguments)]
pub fn stream_table_worker(
    conn: &Connection,
    req: &TableStreamRequest,
    schema: &str,
    name: &str,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let meta = table_meta(conn, schema, name, &req.columns, false)?;
    let tiebreak: Vec<String> = if req.order_by_key {
        if meta.tiebreak.is_empty() {
            vec![ROWID.to_string()]
        } else {
            meta.tiebreak.clone()
        }
    } else {
        Vec::new()
    };
    let sql = format!(
        "SELECT {} FROM {}{}{}",
        meta.select_list,
        meta.quoted_table,
        sql::where_clause(&req.filters, req.raw_where.as_deref())?,
        sql::order_clause(&[], &tiebreak)?
    );
    let params = ExecParams {
        text: String::new(),
        max_rows: None,
        batch_size: batch,
        auto_commit: false,
        read_only: false,
        max_lob,
        keep_open: false,
    };
    run_single_query(conn, &sql, &params, em, ctl)
}

/// Insert many rows with one array DML. Runs in the current transaction; nothing is committed.
pub fn bulk_insert(
    conn: &Connection,
    req: &BulkInsertRequest,
    schema: &str,
    name: &str,
) -> Result<BulkInsertResult> {
    if req.columns.is_empty() {
        return Err(Error::query("bulk insert needs at least one column"));
    }
    if req.rows.is_empty() {
        return Ok(BulkInsertResult::default());
    }
    let table = qualified(schema, name)?;
    let cols = req
        .columns
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Result<Vec<_>>>()?;
    for row in &req.rows {
        if row.len() != req.columns.len() {
            return Err(Error::query(format!(
                "a row has {} values for {} columns",
                row.len(),
                req.columns.len()
            )));
        }
    }
    // Placeholders keep the value kind (dates need a conversion function).
    let first = &req.rows[0];
    let placeholders: Vec<String> = first
        .iter()
        .enumerate()
        .map(|(i, v)| match v {
            EditValue::Default => "DEFAULT".to_string(),
            EditValue::Text(_) => format!(":{}", i + 1),
            EditValue::Value(v) => crate::edit::placeholder(v, i + 1),
        })
        .collect();
    let insert = format!(
        "INSERT INTO {table} ({}) VALUES ({})",
        cols.join(", "),
        placeholders.join(", ")
    );
    match req.on_conflict {
        OnConflict::Error => run_batch(conn, &insert, req, &placeholders),
        OnConflict::Skip => {
            // Rows that violate a unique constraint are skipped (batch errors ORA-00001).
            run_batch_with_errors(conn, &insert, req, &placeholders, false)
        }
        OnConflict::Update => {
            if req.conflict_columns.is_empty() {
                return Err(Error::query("on conflict update needs conflict columns"));
            }
            let merge = merge_sql(&table, req, &placeholders)?;
            run_merge(conn, &merge, req, &placeholders)
        }
    }
}

fn row_binds(
    req: &BulkInsertRequest,
    placeholders: &[String],
    row: &[EditValue],
) -> Result<Vec<Option<Box<dyn ToSql>>>> {
    let _ = req;
    let mut out: Vec<Option<Box<dyn ToSql>>> = Vec::new();
    for (i, v) in row.iter().enumerate() {
        if placeholders[i] == "DEFAULT" {
            continue;
        }
        out.push(Some(match v {
            EditValue::Default => continue,
            EditValue::Text(s) => Box::new(s.clone()) as Box<dyn ToSql>,
            EditValue::Value(v) => bind_of(v)?,
        }));
    }
    Ok(out)
}

fn bind_numbers(placeholders: &[String]) -> Vec<usize> {
    placeholders
        .iter()
        .enumerate()
        .filter(|(_, p)| *p != "DEFAULT")
        .map(|(i, _)| i + 1)
        .collect()
}

fn run_batch(
    conn: &Connection,
    sql: &str,
    req: &BulkInsertRequest,
    placeholders: &[String],
) -> Result<BulkInsertResult> {
    run_batch_with_errors(conn, sql, req, placeholders, true)
}

fn run_batch_with_errors(
    conn: &Connection,
    sql: &str,
    req: &BulkInsertRequest,
    placeholders: &[String],
    fail_on_error: bool,
) -> Result<BulkInsertResult> {
    let total = req.rows.len();
    let mut builder = conn.batch(sql, total);
    if !fail_on_error {
        builder.with_batch_errors();
    }
    let mut batch = builder.build().map_err(map_error)?;
    let numbers = bind_numbers(placeholders);
    for row in &req.rows {
        let binds = row_binds(req, placeholders, row)?;
        let refs: Vec<&dyn ToSql> = binds.iter().filter_map(|b| b.as_deref()).collect();
        // The positional binds of the statement are renumbered 1..n over the non-DEFAULT values.
        let _ = &numbers;
        batch.append_row(&refs).map_err(map_error)?;
    }
    match batch.execute() {
        Ok(()) => Ok(BulkInsertResult {
            inserted: total as u64,
            updated: 0,
            skipped: 0,
        }),
        Err(e) => match e.batch_errors() {
            Some(errors) if !fail_on_error => {
                let skipped = errors.iter().filter(|d| d.code() == 1).count();
                if skipped != errors.len() {
                    // Anything but a duplicate key is a real error.
                    let first = errors
                        .iter()
                        .find(|d| d.code() != 1)
                        .map(|d| d.message().to_string());
                    return Err(Error::query(
                        first.unwrap_or_else(|| "bulk insert failed".into()),
                    ));
                }
                Ok(BulkInsertResult {
                    inserted: (total - skipped) as u64,
                    updated: 0,
                    skipped: skipped as u64,
                })
            }
            _ => Err(map_error(e)),
        },
    }
}

fn merge_sql(table: &str, req: &BulkInsertRequest, placeholders: &[String]) -> Result<String> {
    let cols: Vec<String> = req.columns.clone();
    let using_cols = cols
        .iter()
        .enumerate()
        .map(|(i, c)| {
            let ph = if placeholders[i] == "DEFAULT" {
                "NULL".to_string()
            } else {
                placeholders[i].clone()
            };
            Ok(format!("{ph} AS {}", quote_ident(c)?))
        })
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let on = req
        .conflict_columns
        .iter()
        .map(|c| {
            let q = quote_ident(c)?;
            Ok(format!("t.{q} = s.{q}"))
        })
        .collect::<Result<Vec<_>>>()?
        .join(" AND ");
    let updates = cols
        .iter()
        .filter(|c| !req.conflict_columns.contains(c))
        .map(|c| {
            let q = quote_ident(c)?;
            Ok(format!("t.{q} = s.{q}"))
        })
        .collect::<Result<Vec<_>>>()?;
    let insert_cols = cols
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let insert_vals = cols
        .iter()
        .map(|c| Ok(format!("s.{}", quote_ident(c)?)))
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let matched = if updates.is_empty() {
        String::new()
    } else {
        format!("WHEN MATCHED THEN UPDATE SET {} ", updates.join(", "))
    };
    Ok(format!(
        "MERGE INTO {table} t USING (SELECT {using_cols} FROM dual) s ON ({on}) {matched}\
         WHEN NOT MATCHED THEN INSERT ({insert_cols}) VALUES ({insert_vals})"
    ))
}

fn run_merge(
    conn: &Connection,
    sql: &str,
    req: &BulkInsertRequest,
    placeholders: &[String],
) -> Result<BulkInsertResult> {
    let mut batch = conn
        .batch(sql, req.rows.len())
        .with_row_counts()
        .build()
        .map_err(map_error)?;
    for row in &req.rows {
        let binds = row_binds(req, placeholders, row)?;
        let refs: Vec<&dyn ToSql> = binds.iter().filter_map(|b| b.as_deref()).collect();
        batch.append_row(&refs).map_err(map_error)?;
    }
    batch.execute().map_err(map_error)?;
    // A MERGE row count of 1 is either an insert or an update; count them by existence is not
    // possible afterwards, so report them all as inserted-or-updated in `updated`.
    let counts = batch.row_counts().map_err(map_error)?;
    let affected: u64 = counts.iter().sum();
    Ok(BulkInsertResult {
        inserted: 0,
        updated: affected,
        skipped: req.rows.len() as u64 - affected.min(req.rows.len() as u64),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn select_expressions_convert_unreadable_types() {
        assert_eq!(
            select_expr("A", "NUMBER").unwrap(),
            ("\"A\"".to_string(), false)
        );
        assert_eq!(
            select_expr("J", "JSON").unwrap(),
            (
                "JSON_SERIALIZE(\"J\" RETURNING CLOB) AS \"J\"".to_string(),
                true
            )
        );
        assert!(
            select_expr("V", "VECTOR")
                .unwrap()
                .0
                .contains("FROM_VECTOR")
        );
        assert!(select_expr("B", "BFILE").unwrap().1);
    }

    #[test]
    fn merge_statement_shape() {
        let req = BulkInsertRequest {
            table: dbstudio_core::ObjectPath::root(),
            columns: vec!["ID".into(), "NAME".into()],
            rows: vec![vec![
                EditValue::Text("1".into()),
                EditValue::Text("a".into()),
            ]],
            on_conflict: OnConflict::Update,
            conflict_columns: vec!["ID".into()],
        };
        let ph = vec![":1".to_string(), ":2".to_string()];
        let sql = merge_sql("\"S\".\"T\"", &req, &ph).unwrap();
        assert_eq!(
            sql,
            "MERGE INTO \"S\".\"T\" t USING (SELECT :1 AS \"ID\", :2 AS \"NAME\" FROM dual) s \
             ON (t.\"ID\" = s.\"ID\") WHEN MATCHED THEN UPDATE SET t.\"NAME\" = s.\"NAME\" \
             WHEN NOT MATCHED THEN INSERT (\"ID\", \"NAME\") VALUES (s.\"ID\", s.\"NAME\")"
        );
    }
}
