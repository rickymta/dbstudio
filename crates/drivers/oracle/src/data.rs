/// Column types the OCI binding cannot read; they are converted in the select list.
fn select_expr(column: &str, data_type: &str) -> Result<(String, bool)> {
    let q = quote_ident(column)?;
    let t = data_type.to_ascii_uppercase();
    Ok(match t.as_str() {
        "JSON" => (format!("JSON_SERIALIZE({q} RETURNING CLOB) AS {q}"), true),
        "VECTOR" => (format!("FROM_VECTOR({q}) AS {q}"), true),
        "BFILE" => (
            format!("CASE WHEN {q} IS NULL THEN NULL ELSE '<BFILE>' END AS {q}"),
            true,
        ),
        _ => (q, false),
    })
}

/// What is needed to page through one table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableMeta {
    pub select_list: String,
    /// Columns that make the order deterministic (key, or `ROWID`).
    pub tiebreak: Vec<String>,
    pub quoted_table: String,
    pub kind: ObjectKind,
}

/// Column list, key and kind of `schema.name`.
pub fn table_meta(
    conn: &Connection,
    schema: &str,
    name: &str,
    only: &[String],
    add_rowid: bool,
) -> Result<TableMeta> {
    let kind = catalog::relation_kind(conn, schema, name)?
        .ok_or_else(|| Error::NotFound(format!("table or view {schema}.{name}")))?;
    let cols = rows(
        conn,
        "SELECT column_name, data_type FROM all_tab_cols \
         WHERE owner = :1 AND table_name = :2 AND hidden_column = 'NO' AND column_id IS NOT NULL \
         ORDER BY column_id",
        &[&schema, &name],
    )?;
    let mut exprs = Vec::new();
    let mut rewritten = false;
    let wanted: Vec<&String> = only.iter().collect();
    for name in &wanted {
        if !cols.iter().any(|c| cell(c, 0) == **name) {
            return Err(Error::query(format!(
                "no column \"{name}\" in {schema}.{}",
                "the table"
            )));
        }
    }
    for c in &cols {
        let column = cell(c, 0);
        if !only.is_empty() && !only.contains(&column) {
            continue;
        }
        let (expr, changed) = select_expr(&column, &cell(c, 1))?;
        rewritten |= changed;
        exprs.push(expr);
    }
    // Key for deterministic paging.
    let tiebreak = if kind == ObjectKind::View {
        Vec::new()
    } else {
        let info = catalog::key_info(conn, schema, name)?;
        if !info.primary_key.is_empty() {
            info.primary_key
        } else if let Some(u) = info.unique_keys.first() {
            u.clone()
        } else {
            vec![ROWID.to_string()]
        }
    };
    let select_list = if rewritten || !only.is_empty() || add_rowid {
        let mut l = exprs;
        if add_rowid && tiebreak == [ROWID.to_string()] {
            l.push(format!("ROWID AS {}", quote_ident(ROWID)?));
        }
        l.join(", ")
    } else {
        "*".to_string()
    };
    Ok(TableMeta {
        select_list,
        tiebreak,
        quoted_table: qualified(schema, name)?,
        kind,
    })
}

/// Everything `fetch_table` needs, built on the worker.
#[allow(clippy::too_many_arguments)]
pub fn fetch_table_worker(
    conn: &Connection,
    schema: &str,
    name: &str,
    filters: &[ColumnFilter],
    raw_where: Option<&str>,
    sort: &[SortKey],
    offset: u64,
    limit: u64,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let meta = table_meta(conn, schema, name, &[], true)?;
    let sql = sql::select_sql(
        &meta.select_list,
        &meta.quoted_table,
        filters,
        raw_where,
        sort,
        &meta.tiebreak,
        offset,
        limit,
    )?;
    read_only_query(conn, &sql, batch, max_lob, em, ctl)
}

/// Run one `SELECT` generated by the driver inside `SET TRANSACTION READ ONLY` (a consistent
/// snapshot) and end the transaction afterwards.
pub fn read_only_query(
    conn: &Connection,
    sql: &str,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let params = ExecParams {
        text: String::new(),
        max_rows: None,
        batch_size: batch,
        auto_commit: false,
        read_only: false,
        max_lob,
        keep_open: false,
    };
    let _ = conn.rollback();
    let _ = conn.execute("SET TRANSACTION READ ONLY", &[]);
    let mut result = run_single_query(conn, sql, &params, em, ctl);
    let _ = conn.rollback();
    if result.as_ref().is_err_and(is_snapshot_too_old) {
        // The table was (re)defined within the resolution of the snapshot clock (ORA-01466): read
        // the current state instead of failing.
        result = run_single_query(conn, sql, &params, em, ctl);
        let _ = conn.rollback();
    }
    result
}

/// `ORA-01466`: a read-only snapshot is older than the last DDL of a table.
fn is_snapshot_too_old(e: &Error) -> bool {
    e.to_string().contains("ORA-01466")
}

/// `SELECT COUNT(*)` of a table with filters.
pub fn count_worker(
    conn: &Connection,
    schema: &str,
    name: &str,
    filters: &[ColumnFilter],
    raw_where: Option<&str>,
) -> Result<u64> {
    let table = qualified(schema, name)?;
    let sql = sql::count_sql(&table, filters, raw_where)?;
    let _ = conn.rollback();
    let _ = conn.execute("SET TRANSACTION READ ONLY", &[]);
    let mut result = catalog::scalar(conn, &sql, &[]);
    let _ = conn.rollback();
    if result.as_ref().is_err_and(is_snapshot_too_old) {
        result = catalog::scalar(conn, &sql, &[]);
        let _ = conn.rollback();
    }
    result?
        .and_then(|v| v.trim().parse::<u64>().ok())
        .ok_or_else(|| Error::Other("COUNT(*) returned no number".into()))
}

/// Stream a whole table (export / backup) on the connection, inside its current transaction.
#[allow(clippy::too_many_arguments)]
pub fn stream_table_worker(
    conn: &Connection,
    req: &TableStreamRequest,
    schema: &str,
    name: &str,
    batch: usize,
    max_lob: u64,
    em: &Emitter,
    ctl: &Control,
) -> Result<()> {
    let meta = table_meta(conn, schema, name, &req.columns, false)?;
    let tiebreak: Vec<String> = if req.order_by_key {
        if meta.tiebreak.is_empty() {
            vec![ROWID.to_string()]
        } else {
            meta.tiebreak.clone()
        }
    } else {
        Vec::new()
    };
    let sql = format!(
        "SELECT {} FROM {}{}{}",
        meta.select_list,
        meta.quoted_table,
        sql::where_clause(&req.filters, req.raw_where.as_deref())?,
        sql::order_clause(&[], &tiebreak)?
    );
    let params = ExecParams {
        text: String::new(),
        max_rows: None,
        batch_size: batch,
        auto_commit: false,
        read_only: false,
        max_lob,
        keep_open: false,
    };
    run_single_query(conn, &sql, &params, em, ctl)
}

/// Insert many rows with array DML (one per statement shape). Runs in the current transaction; nothing is committed.
pub fn bulk_insert(
    conn: &Connection,
    req: &BulkInsertRequest,
    schema: &str,
    name: &str,
) -> Result<BulkInsertResult> {
    if req.columns.is_empty() {
        return Err(Error::query("bulk insert needs at least one column"));
    }
    if req.rows.is_empty() {
        return Ok(BulkInsertResult::default());
    }
    let table = qualified(schema, name)?;
    let cols = req
        .columns
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Result<Vec<_>>>()?;
    for row in &req.rows {
        if row.len() != req.columns.len() {
            return Err(Error::query(format!(
                "a row has {} values for {} columns",
                row.len(),
                req.columns.len()
            )));
        }
    }
    // Rows are grouped by the shape of their statement: a cell left to DEFAULT is left out of the
    // INSERT column list (so the column default applies) and a value kind may need a conversion
    // function, so rows of different shapes cannot share one array DML.
    let mut groups: Vec<(Vec<String>, Vec<&[EditValue]>)> = Vec::new();
    for row in &req.rows {
        let shape = row_placeholders(row);
        match groups.iter_mut().find(|(s, _)| *s == shape) {
            Some((_, rows)) => rows.push(row),
            None => groups.push((shape, vec![row])),
        }
    }
    let mut total = BulkInsertResult::default();
    for (shape, rows) in &groups {
        let part = match req.on_conflict {
            OnConflict::Error | OnConflict::Skip => {
                let insert = insert_sql(&table, &cols, shape);
                // Skip: rows that violate a unique constraint are skipped (batch errors ORA-00001).
                run_batch(
                    conn,
                    &insert,
                    rows,
                    matches!(req.on_conflict, OnConflict::Error),
                )?
            }
            OnConflict::Update => {
                if req.conflict_columns.is_empty() {
                    return Err(Error::query("on conflict update needs conflict columns"));
                }
                let merge = merge_sql(&table, req, shape)?;
                run_merge(conn, &merge, rows)?
            }
        };
        total.inserted += part.inserted;
        total.updated += part.updated;
        total.skipped += part.skipped;
    }
    Ok(total)
}

/// Placeholder of every column of `row` (`DEFAULT` for a cell left to the column default); the
/// binds are numbered over the non-`DEFAULT` cells only.
fn row_placeholders(row: &[EditValue]) -> Vec<String> {
    let mut n = 0;
    row.iter()
        .map(|v| match v {
            EditValue::Default => "DEFAULT".to_string(),
            EditValue::Text(_) => {
                n += 1;
                format!(":{n}")
            }
            EditValue::Value(v) => {
                n += 1;
                crate::edit::placeholder(v, n)
            }
        })
        .collect()
}

/// `INSERT` without the columns whose cell is `DEFAULT`, so that their default applies.
fn insert_sql(table: &str, cols: &[String], placeholders: &[String]) -> String {
    let (names, values): (Vec<&str>, Vec<&str>) = cols
        .iter()
        .zip(placeholders)
        .filter(|(_, p)| *p != "DEFAULT")
        .map(|(c, p)| (c.as_str(), p.as_str()))
        .unzip();
    if names.is_empty() {
        return format!("INSERT INTO {table} VALUES (DEFAULT)");
    }
    format!(
        "INSERT INTO {table} ({}) VALUES ({})",
        names.join(", "),
        values.join(", ")
    )
}

fn row_binds(row: &[EditValue]) -> Result<Vec<Box<dyn ToSql>>> {
    let mut out: Vec<Box<dyn ToSql>> = Vec::new();
    for v in row {
        match v {
            EditValue::Default => {}
            EditValue::Text(s) => out.push(Box::new(s.clone())),
            EditValue::Value(v) => out.push(bind_of(v)?),
        }
    }
    Ok(out)
}

fn run_batch(
    conn: &Connection,
    sql: &str,
    rows: &[&[EditValue]],
    fail_on_error: bool,
) -> Result<BulkInsertResult> {
    let total = rows.len();
    let mut builder = conn.batch(sql, total);
    if !fail_on_error {
        builder.with_batch_errors();
    }
    let mut batch = builder.build().map_err(map_error)?;
    for row in rows {
        let binds = row_binds(row)?;
        let refs: Vec<&dyn ToSql> = binds.iter().map(|b| b.as_ref()).collect();
        batch.append_row(&refs).map_err(map_error)?;
    }
    match batch.execute() {
        Ok(()) => Ok(BulkInsertResult {
            inserted: total as u64,
            updated: 0,
            skipped: 0,
        }),
        Err(e) => match e.batch_errors() {
            Some(errors) if !fail_on_error => {
                let skipped = errors.iter().filter(|d| d.code() == 1).count();
                if skipped != errors.len() {
                    // Anything but a duplicate key is a real error.
                    let first = errors
                        .iter()
                        .find(|d| d.code() != 1)
                        .map(|d| d.message().to_string());
                    return Err(Error::query(
                        first.unwrap_or_else(|| "bulk insert failed".into()),
                    ));
                }
                Ok(BulkInsertResult {
                    inserted: (total - skipped) as u64,
                    updated: 0,
                    skipped: skipped as u64,
                })
            }
            _ => Err(map_error(e)),
        },
    }
}

fn merge_sql(table: &str, req: &BulkInsertRequest, placeholders: &[String]) -> Result<String> {
    let cols: Vec<String> = req.columns.clone();
    let using_cols = cols
        .iter()
        .enumerate()
        .map(|(i, c)| {
            let ph = if placeholders[i] == "DEFAULT" {
                "NULL".to_string()
            } else {
                placeholders[i].clone()
            };
            Ok(format!("{ph} AS {}", quote_ident(c)?))
        })
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let on = req
        .conflict_columns
        .iter()
        .map(|c| {
            let q = quote_ident(c)?;
            Ok(format!("t.{q} = s.{q}"))
        })
        .collect::<Result<Vec<_>>>()?
        .join(" AND ");
    let updates = cols
        .iter()
        .filter(|c| !req.conflict_columns.contains(c))
        .map(|c| {
            let q = quote_ident(c)?;
            Ok(format!("t.{q} = s.{q}"))
        })
        .collect::<Result<Vec<_>>>()?;
    let insert_cols = cols
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let insert_vals = cols
        .iter()
        .map(|c| Ok(format!("s.{}", quote_ident(c)?)))
        .collect::<Result<Vec<_>>>()?
        .join(", ");
    let matched = if updates.is_empty() {
        String::new()
    } else {
        format!("WHEN MATCHED THEN UPDATE SET {} ", updates.join(", "))
    };
    Ok(format!(
        "MERGE INTO {table} t USING (SELECT {using_cols} FROM dual) s ON ({on}) {matched}\
         WHEN NOT MATCHED THEN INSERT ({insert_cols}) VALUES ({insert_vals})"
    ))
}

fn run_merge(conn: &Connection, sql: &str, rows: &[&[EditValue]]) -> Result<BulkInsertResult> {
    let mut batch = conn
        .batch(sql, rows.len())
        .with_row_counts()
        .build()
        .map_err(map_error)?;
    for row in rows {
        let binds = row_binds(row)?;
        let refs: Vec<&dyn ToSql> = binds.iter().map(|b| b.as_ref()).collect();
        batch.append_row(&refs).map_err(map_error)?;
    }
    batch.execute().map_err(map_error)?;
    // A MERGE row count of 1 is either an insert or an update; count them by existence is not
    // possible afterwards, so report them all as inserted-or-updated in `updated`.
    let counts = batch.row_counts().map_err(map_error)?;
    let affected: u64 = counts.iter().sum();
    Ok(BulkInsertResult {
        inserted: 0,
        updated: affected,
        skipped: rows.len() as u64 - affected.min(rows.len() as u64),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn select_expressions_convert_unreadable_types() {
        assert_eq!(
            select_expr("A", "NUMBER").unwrap(),
            ("\"A\"".to_string(), false)
        );
        assert_eq!(
            select_expr("J", "JSON").unwrap(),
            (
                "JSON_SERIALIZE(\"J\" RETURNING CLOB) AS \"J\"".to_string(),
                true
            )
        );
        assert!(
            select_expr("V", "VECTOR")
                .unwrap()
                .0
                .contains("FROM_VECTOR")
        );
        assert!(select_expr("B", "BFILE").unwrap().1);
    }

    #[test]
    fn default_cells_are_left_out_of_the_insert() {
        let row = [
            EditValue::Text("1".into()),
            EditValue::Default,
            EditValue::Value(dbstudio_core::Value::Date("2024-01-01".into())),
        ];
        let ph = row_placeholders(&row);
        assert_eq!(ph, [":1", "DEFAULT", "TO_DATE(:2, 'YYYY-MM-DD')"]);
        let cols: Vec<String> = ["\"A\"", "\"B\"", "\"C\""].map(String::from).to_vec();
        assert_eq!(
            insert_sql("\"S\".\"T\"", &cols, &ph),
            "INSERT INTO \"S\".\"T\" (\"A\", \"C\") VALUES (:1, TO_DATE(:2, 'YYYY-MM-DD'))"
        );
        assert_eq!(row_binds(&row).unwrap().len(), 2);
        assert_eq!(
            insert_sql("T", &cols[..1], &["DEFAULT".to_string()]),
            "INSERT INTO T VALUES (DEFAULT)"
        );
    }

    #[test]
    fn merge_statement_shape() {
        let req = BulkInsertRequest {
            table: dbstudio_core::ObjectPath::root(),
            columns: vec!["ID".into(), "NAME".into()],
            rows: vec![vec![
                EditValue::Text("1".into()),
                EditValue::Text("a".into()),
            ]],
            on_conflict: OnConflict::Update,
            conflict_columns: vec!["ID".into()],
        };
        let ph = vec![":1".to_string(), ":2".to_string()];
        let sql = merge_sql("\"S\".\"T\"", &req, &ph).unwrap();
        assert_eq!(
            sql,
            "MERGE INTO \"S\".\"T\" t USING (SELECT :1 AS \"ID\", :2 AS \"NAME\" FROM dual) s \
             ON (t.\"ID\" = s.\"ID\") WHEN MATCHED THEN UPDATE SET t.\"NAME\" = s.\"NAME\" \
             WHEN NOT MATCHED THEN INSERT (\"ID\", \"NAME\") VALUES (s.\"ID\", s.\"NAME\")"
        );
    }
}
