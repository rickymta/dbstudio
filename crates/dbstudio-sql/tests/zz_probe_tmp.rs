fn show(d: D, t: &str) {
    let a = dbstudio_sql::analyze(d, t);
    let ro = matches!(
        check(
            &Policy {
                read_only: true,
                production: false,
                confirm_text: String::new()
            },
            &a
        ),
        Verdict::Allow
    );
    let v: Vec<String> = a
        .statements
        .iter()
        .map(|s| format!("[{:?} {:?} '{}']", s.class, s.destructive, s.verb))
        .collect();
    println!(
        "{:?} | {:?} | RO_ALLOW={} | {} | probs={}",
        short(d),
        t,
        ro,
        v.join(" "),
        a.problems.len()
    );
}
fn short(d: D) -> &'static str {
    match d {
        D::Postgres => "PG",
        D::MySql { .. } => "MY",
        D::MsSql => "MS",
        D::Oracle => "ORA",
        D::MongoShell => "MONGO",
        D::RedisCli => "REDIS",
        D::Opaque => "OPQ",
    }
}

