/** Descriptor of the driver for `kind` (mock registry). */
export function mockDriverFor(kind: DbKind): DriverDescriptor {
  const d = mockDrivers.find((x) => x.kind === kind);
  if (!d) throw new Error(`unknown kind ${kind}`);
  return d;
}

